#!/bin/bash

# Скрипт для принудительного обновления сервера с последними изменениями
# Используется когда есть локальные конфликты на сервере

echo "=== ПРИНУДИТЕЛЬНОЕ ОБНОВЛЕНИЕ СЕРВЕРА ==="
echo "Это удалит все локальные изменения и заменит их версией из репозитория"

cd /root/CRM || exit 1

# Остановка контейнеров
echo "Останавливаем контейнеры..."
docker-compose down

# Сохранение текущих изменений в stash (на всякий случай)
echo "Сохраняем локальные изменения в stash..."
git stash push -m "Local changes before force update $(date)"

# Принудительный сброс к HEAD
echo "Сбрасываем к HEAD..."
git reset --hard HEAD

# Получение последних изменений
echo "Получаем последние изменения из репозитория..."
git fetch origin development

# Принудительное слияние
echo "Принудительно обновляемся до последней версии..."
git reset --hard origin/development

# Проверка статуса
echo "Статус после обновления:"
git status

echo "=== ОБНОВЛЕНИЕ ЗАВЕРШЕНО ==="
echo "Теперь можно пересобрать и запустить контейнеры:"
echo "docker-compose build --no-cache"
echo "docker-compose up -d"
